-- V1: Tabelle so, wie Hibernate sie früher mit ddl-auto=update angelegt hat.
-- IF NOT EXISTS: Auf bestehenden Datenbanken (lokal, Render) passiert hier nichts,
-- auf einer leeren Datenbank entsteht derselbe Ausgangszustand.
CREATE TABLE IF NOT EXISTS task (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description varchar(255),
    done        boolean NOT NULL,
    name        varchar(255)
);
