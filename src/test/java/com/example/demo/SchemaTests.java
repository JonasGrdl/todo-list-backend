package com.example.demo;

import javax.sql.DataSource;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
class SchemaTests {
    @Autowired DataSource db;

    @Test void upgradesLegacyRowsWithoutLosingData() throws Exception {
        checkMigration(true);
    }

    @Test void addsMissingDoneColumnToExistingTable() throws Exception {
        checkMigration(false);
    }

    private void checkMigration(boolean hasDone) throws Exception {
        try(var c=db.getConnection();var s=c.createStatement()) {
            c.setAutoCommit(false);
            try {
                s.execute("CREATE SCHEMA legacy_fixture");
                s.execute("SET LOCAL search_path TO legacy_fixture");
                s.execute("CREATE TABLE task (id bigint generated by default as identity primary key, name varchar(255), description varchar(255)" + (hasDone ? ", done boolean not null" : "") + ")");
                s.execute(hasDone ? "INSERT INTO task (name,description,done) VALUES ('Alter Task','Unverändert',true)" : "INSERT INTO task (name,description) VALUES ('Alter Task','Unverändert')");
                var migration=new ResourceDatabasePopulator(new ClassPathResource("schema.sql"));
                migration.setSeparator("@@");
                migration.populate(c);
                migration.populate(c);
                try(var rows=s.executeQuery("SELECT * FROM task")) {
                    assertTrue(rows.next());
                    assertEquals(1,rows.getLong("id"));
                    assertEquals("Alter Task",rows.getString("name"));
                    assertEquals("Unverändert",rows.getString("description"));
                    assertEquals(hasDone, rows.getBoolean("done"));
                    assertEquals("mittel",rows.getString("priority"));
                    assertNotNull(rows.getTimestamp("created_at"));
                    assertNull(rows.getDate("due_date"));
                    assertFalse(rows.next());
                }
            } finally { c.rollback(); }
        }
    }
}
