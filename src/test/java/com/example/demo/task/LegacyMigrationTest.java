package com.example.demo.task;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;

/**
 * Prüft, dass die Flyway-Migration eine Datenbank aus der alten Version
 * (Tabelle von Hibernate ddl-auto=update, ohne Flyway-Historie) übernimmt,
 * ohne Daten zu verlieren. Genau dieser Fall tritt beim ersten Deployment auf Render auf.
 */
@Testcontainers
class LegacyMigrationTest {

    @Container
    static PostgreSQLContainer postgres = new PostgreSQLContainer("postgres:16-alpine");

    @Test
    void migratesExistingRowsWithoutLosingData() throws Exception {
        String longTitle = "L".repeat(200);
        try (Connection c = connect(); Statement s = c.createStatement()) {
            // Schema exakt wie im Dump der bisherigen Datenbank
            s.execute("""
                    CREATE TABLE task (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      description varchar(255), done boolean NOT NULL, name varchar(255))""");
            s.execute("INSERT INTO task (description, done, name) VALUES ('Milestone 5', true, 'Web-Tech Abgabe')");
            s.execute("INSERT INTO task (description, done, name) VALUES (NULL, false, '  Lernen  ')");
            s.execute("INSERT INTO task (description, done, name) VALUES ('alt', false, '" + longTitle + "')");
            s.execute("INSERT INTO task (description, done, name) VALUES ('ohne Namen', false, '   ')");
        }

        Flyway.configure()
                .dataSource(postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword())
                .baselineOnMigrate(true)
                .baselineVersion("0")
                .load()
                .migrate();

        try (Connection c = connect(); Statement s = c.createStatement()) {
            ResultSet rs = s.executeQuery(
                    "SELECT id, title, description, status, priority, due_date, created_at FROM task ORDER BY id");

            assertThat(rs.next()).isTrue();
            assertThat(rs.getString("title")).isEqualTo("Web-Tech Abgabe");
            assertThat(rs.getString("description")).isEqualTo("Milestone 5");
            assertThat(rs.getString("status")).isEqualTo("DONE");
            assertThat(rs.getString("priority")).isEqualTo("MEDIUM");
            assertThat(rs.getObject("due_date")).isNull();
            assertThat(rs.getObject("created_at")).isNotNull();

            assertThat(rs.next()).isTrue();
            assertThat(rs.getString("title")).isEqualTo("Lernen");
            assertThat(rs.getString("status")).isEqualTo("OPEN");

            assertThat(rs.next()).isTrue();
            assertThat(rs.getString("title")).hasSize(120);
            assertThat(rs.getString("description")).isEqualTo("Ursprünglicher Titel: " + longTitle + "\n\nalt");

            assertThat(rs.next()).isTrue();
            assertThat(rs.getString("title")).isEqualTo("Ohne Titel");
            assertThat(rs.getString("description")).isEqualTo("ohne Namen");

            assertThat(rs.next()).isFalse();

            // Neue Zeilen bekommen weiterhin automatisch eine freie id
            ResultSet inserted = s.executeQuery("""
                    INSERT INTO task (title, status, priority, created_at, updated_at)
                    VALUES ('Neu', 'OPEN', 'LOW', now(), now()) RETURNING id""");
            inserted.next();
            assertThat(inserted.getLong(1)).isEqualTo(5);
        }
    }

    private static Connection connect() throws Exception {
        return DriverManager.getConnection(postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword());
    }
}
